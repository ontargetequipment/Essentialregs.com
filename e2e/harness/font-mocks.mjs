#!/usr/bin/env node
/**
 * Writes the module NEXT_FONT_GOOGLE_MOCKED_RESPONSES points at, for a build with no route to
 * fonts.googleapis.com: node e2e/harness/font-mocks.mjs <out.cjs> <font-base-url>
 *
 * next/font/google fetches one stylesheet per font at build time. Turbopack (the Next 16 default)
 * looks the mocked stylesheet up by the exact URL it would have fetched, so the URLs are rebuilt here
 * from the app's own `next/font/google` calls (src/**\/*.tsx: family, weight list, display), the same
 * way getGoogleFontsUrl does. Each stylesheet is one @font-face per weight. The mock hook covers only the
 * stylesheet: Turbopack still downloads every font file the stylesheet names, so they point at the mock
 * Supabase server (GET /__harness/font/*, a few placeholder bytes). The browser gets an unreadable font and
 * shows the system fallback, as it does while a real font loads.
 */
import fs from "node:fs";
import path from "node:path";

const [out, fontBase] = process.argv.slice(2);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "..");

function* walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (/\.(t|j)sx?$/.test(e.name)) yield p;
  }
}

const mocks = {};
for (const file of walk(path.join(ROOT, "src"))) {
  const src = fs.readFileSync(file, "utf8");
  const imp = /import\s*\{([^}]*)\}\s*from\s*["']next\/font\/google["']/.exec(src);
  if (!imp) continue;
  for (const name of imp[1].split(",").map((s) => s.trim()).filter(Boolean)) {
    const call = new RegExp(`${name}\\(\\{([\\s\\S]*?)\\}\\)`).exec(src);
    if (!call) continue;
    const opts = call[1];
    const weights = (/weight:\s*\[([^\]]*)\]/.exec(opts)?.[1] ?? "").match(/\d+/g) ?? [];
    const display = /display:\s*["'](\w+)["']/.exec(opts)?.[1] ?? "swap";
    const family = name.replace(/_/g, "+");
    const sorted = [...weights].sort((a, b) => Number(a) - Number(b));
    const url = `https://fonts.googleapis.com/css2?family=${family}${sorted.length ? `:wght@${sorted.join(";")}` : ""}&display=${display}`;
    mocks[url] = (sorted.length ? sorted : ["400"])
      .map(
        (w) =>
          `/* latin */\n@font-face {\n  font-family: '${name.replace(/_/g, " ")}';\n  font-style: normal;\n  font-weight: ${w};\n  font-display: ${display};\n  src: url(${fontBase}/${family.toLowerCase()}-${w}.woff2) format('woff2');\n  unicode-range: U+0000-00FF;\n}\n`,
      )
      .join("");
  }
}
fs.writeFileSync(out, `// Generated by e2e/harness/font-mocks.mjs\nmodule.exports = ${JSON.stringify(mocks, null, 2)};\n`);
console.log(`font-mocks: ${Object.keys(mocks).length} stylesheet(s) -> ${out}`);
